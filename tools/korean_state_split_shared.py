class SplitSharedError(ValueError):
    pass


@dataclass
class Node:
    start: int
    end: int
    key: str
    op: str = ""
    value: str = ""
    opening: int | None = None
    closing: int | None = None
    children: list["Node"] = field(default_factory=list)
    parent: "Node | None" = field(default=None, repr=False)

    @property
    def block(self) -> bool:
        return self.opening is not None


def parse(text: str) -> list[Node]:
    """Read assignment/list structure without normalizing any source bytes."""
    tokens = [m for m in TOKEN.finditer(text) if not m.group().startswith("#")]

    def sequence(index: int, parent: Node | None) -> tuple[list[Node], int]:
        nodes: list[Node] = []
        while index < len(tokens) and tokens[index].group() != "}":
            first = tokens[index]
            key = first.group()
            if key == "{":
                raise SplitSharedError(f"unexpected anonymous block at {first.start()}")
            if index + 2 < len(tokens) and tokens[index + 1].group() in {"=", ">", "<", ">=", "<=", "!="}:
                op, value = tokens[index + 1].group(), tokens[index + 2]
                node = Node(first.start(), value.end(), key, op, value.group(), parent=parent)
                index += 3
                if value.group() == "{":
                    node.opening = value.start()
                    node.children, index = sequence(index, node)
                    if index >= len(tokens) or tokens[index].group() != "}":
                        raise SplitSharedError(f"unclosed {key} at {first.start()}")
                    node.closing = tokens[index].start()
                    node.end = tokens[index].end()
                    index += 1
            else:
                node = Node(first.start(), first.end(), key, parent=parent)
                index += 1
            nodes.append(node)
        return nodes, index

    nodes, last = sequence(0, None)
    if last != len(tokens):
        raise SplitSharedError("unmatched closing brace")
    return nodes


def walk(nodes: list[Node]):
    for node in nodes:
        yield node
        yield from walk(node.children)


def _ancestors(node: Node):
    parent = node.parent
    while parent is not None:
        yield parent
        parent = parent.parent


def _indent(text: str, start: int) -> str:
    prefix = text[text.rfind("\n", 0, start) + 1:start]
    return re.match(r"[ \t]*", prefix).group()


def _splice(text: str, edits: list[tuple[int, int, str]]) -> str:
    end = len(text)
    for start, stop, replacement in sorted(edits, reverse=True):
        if not 0 <= start <= stop <= end:
            raise SplitSharedError("overlapping or invalid shared-file edits")
        text = text[:start] + replacement + text[stop:]
        end = start
    return text


def _condition(node: Node) -> bool:
    for ancestor in _ancestors(node):
        key = ancestor.key.lower()
        if key in CONDITION_CONTEXTS:
            return True
        if key in EFFECT_CONTEXTS:
            return False
    return False


def _scope_clone(block: str, old: int, new: int) -> str:
    return re.sub(rf"^{old}(?=\s*=)", str(new), block, count=1)


def _rename_region(text: str, old: int, new: int) -> str:
    edits = []
    for node in walk(parse(text)):
        if node.block and node.key == str(old):
            edits.append((node.start, node.start + len(node.key), str(new)))
        elif not node.block and node.op == "=" and node.value == str(old) and node.key in CONDITIONS | TRANSFERS | {"state", "attacker", "defender"}:
            end = node.end
            edits.append((end - len(node.value), end, str(new)))
    return _splice(text, edits)


def _named(nodes: list[Node], key: str) -> Node:
    matches = [n for n in walk(nodes) if n.block and n.key == key]
    if len(matches) != 1:
        raise SplitSharedError(f"expected one {key}, found {len(matches)}")
    return matches[0]


def _membership_block(text: str, node: Node, ids: tuple[int, ...], newline: str) -> str:
    indent = _indent(text, node.start)
    return (f"{node.key} = {{{newline}" +
            "".join(f"{indent}\tstate = {state}{newline}" for state in ids) + f"{indent}}}")


def _groups(mapping: Mapping[int, int]):
    missing = sorted({child for _, child in REGIONS} - mapping.keys())
    if missing:
        raise SplitSharedError(f"missing new state mappings: {missing}")
    pairs = {EXISTING[old]: mapping[child] for old, child in REGIONS}
    if len(set(pairs.values())) != 6 or set(pairs) & set(pairs.values()):
        raise SplitSharedError("successor IDs must be distinct from retained state IDs")
    north = (527, pairs[527], 918, pairs[918], 917, pairs[917])
    south = (525, 1144, 1145, pairs[1145], 920, pairs[920], 919, pairs[919], 1146)
    return pairs, north, south


def _sea_groups(text: str, north: tuple[int, ...], south: tuple[int, ...], newline: str) -> str:
    nodes = parse(text)
    filters = [n for n in walk(nodes) if n.block and n.key == "states_filter"
               and any(a.key == "start_civil_war" for a in _ancestors(n))
               and any(c.key == "is_controlled_by" and c.value == "ROOT" for c in n.children)]
    target = []
    for node in filters:
        ors = [c for c in node.children if c.block and c.key == "OR"]
        if len(ors) != 1:
            continue
        group = ors[0]
        ids = {int(c.value) for c in group.children if c.key == "state" and c.value.isdigit()}
        if ids == {918, 527, 525}:
            target.append((group, north + (525,)))
        elif ids == {919, 920, 917, 1144, 1145, 1146}:
            target.append((group, tuple(i for i in south if i != 525)))
    if len(target) != 2:
        raise SplitSharedError(f"SEA civil-war filters expected two reviewed sets, found {len(target)}")
    return _splice(text, [(n.start, n.end, _membership_block(text, n, ids, newline)) for n, ids in target])


def _trigger_groups(text: str, north: tuple[int, ...], south: tuple[int, ...], newline: str) -> str:
    nodes = parse(text)
    edits = []
    for key, ids in (("is_korean_state", south + north), ("is_south_korean_state", south), ("is_north_korean_state", north)):
        parent = _named(nodes, key)
        groups = [n for n in parent.children if n.block and n.key == "OR"]
        if len(groups) != 1:
            raise SplitSharedError(f"{key}: expected direct OR membership")
        group = groups[0]
        edits.append((group.start, group.end, _membership_block(text, group, ids, newline)))
    return _splice(text, edits)


def _move_jap_border(text: str, target: int) -> str:
    nodes = parse(text)
    first = _named(nodes, "JAP_test_the_soviets")
    selected = [n for n in walk(nodes) if n.start >= first.start and
                ((n.block and n.key == "918") or
                 (not n.block and n.value == "918" and n.key in {"state", "attacker", "defender"}))]
    count = len(selected)
    if count != 24:
        raise SplitSharedError(f"JAP Soviet border lifecycle expected 24 Hamgyong references, found {count}")
    edits = [(n.start, n.start + len(n.key), str(target)) if n.block
             else (n.end - len(n.value), n.end, str(target)) for n in selected]
    return _splice(text, edits)


def _single_region_if(node: Node, text: str, pairs: Mapping[int, int], relative: str) -> int | None:
    if node.key.lower() != "if" or relative not in {"events/WTT_PRC.txt", "events/r56_japan.txt"}:
        return None
    descendants = list(walk(node.children))
    ids = {int(n.key) for n in descendants if n.block and n.key.isdigit() and int(n.key) in pairs}
    ids |= {int(n.value) for n in descendants if not n.block and n.value.isdigit()
            and int(n.value) in pairs and n.key in CONDITIONS | TRANSFERS}
    if len(ids) != 1:
        return None
    # Transfer and owner-notification branches are per state, not all-region gates.
    if relative == "events/WTT_PRC.txt" and any(n.key == "transfer_state" for n in descendants):
        return ids.pop()
    if relative == "events/r56_japan.txt" and any(n.key == "country_event" for n in descendants) and any(n.key == "has_country_flag" and n.value == "sfl_kor_fired" for n in descendants):
        return ids.pop()
    return None


def _fort_scopes(text: str, node: Node, block: str, new: int, newline: str) -> str | None:
    if int(node.key) not in {527, 918} or _condition(node):
        return None
    buildings = [n for n in node.children if n.key == "add_building_construction" and n.block]
    if not buildings:
        return None
    new_provinces = ({912, 6963, 9795, 9918, 11775, 11828, 11835, 11896} if node.key == "527"
                     else {898, 959, 3803, 3860, 6822, 6922, 6944, 11878})
    old_edits: list[tuple[int, int, str]] = []
    moved = []
    for building in buildings:
        province = [n for n in building.children if n.key == "province"]
        if len(province) != 1:
            continue  # Non-province factory reward stays in its retained-ID successor.
        p = province[0]
        if not p.block:
            if p.value.isdigit() and int(p.value) in new_provinces:
                moved.append(text[building.start:building.end])
                old_edits.append((building.start - node.start, building.end - node.start, ""))
            continue
        ids = [n for n in p.children if n.key == "id" and n.value.isdigit()]
        selected = [n for n in ids if int(n.value) in new_provinces]
        if not selected:
            continue
        original = text[building.start:building.end]
        other = [n for n in ids if n not in selected]
        if other:
            new_building = _splice(original, [(n.start-building.start, n.end-building.start, "") for n in other])
            old_building = _splice(original, [(n.start-building.start, n.end-building.start, "") for n in selected])
            old_edits.append((building.start-node.start, building.end-node.start, old_building))
            moved.append(new_building)
        else:
            old_edits.append((building.start-node.start, building.end-node.start, ""))
            moved.append(original)
    if not moved:
        return None
    retained = _splice(block, old_edits)
    indent = _indent(text, node.start)
    added = (f"{new} = {{{newline}" +
             (newline + indent + "\t").join(indent + "\t" + item for item in moved) +
             f"{newline}{indent}}}")
    return retained + newline + indent + added


def apply_shared(relative: str, data: bytes, state_id_map: Mapping[int, int], *,
                 expected_before_sha256: str | None = None) -> bytes:
    """Transform one reviewed host-based input; reject drift and repeat application."""
    relative = Path(relative).as_posix()
    if relative not in SHARED_PATHS:
        return data
    if expected_before_sha256 is not None and hashlib.sha256(data).hexdigest().upper() != expected_before_sha256.upper():
        raise SplitSharedError(f"shared split input hash mismatch: {relative}")
    bom = data.startswith(b"\xef\xbb\xbf")
    text = data.decode("utf-8-sig")
    if HEADER in text:
        raise SplitSharedError(f"shared split already applied: {relative}")
    newline = "\r\n" if "\r\n" in text else "\n"
    pairs, north, south = _groups(state_id_map)
    if relative == "events/SEA_Japan.txt":
        result = _sea_groups(text, north, south, newline)
    elif relative == "common/scripted_triggers/JAP_scripted_triggers.txt":
        result = _trigger_groups(text, north, south, newline)
    else:
        if relative == "common/decisions/JAP.txt":
            text = _move_jap_border(text, pairs[918])
        nodes = parse(text)

        def render(node: Node) -> str:
            raw = text[node.start:node.end]
            region = _single_region_if(node, text, pairs, relative)
            if region is not None:
                return raw + newline + _indent(text, node.start) + _rename_region(raw, region, pairs[region])
            if not node.block:
                if node.op != "=" or not node.value.isdigit() or int(node.value) not in pairs:
                    return raw
                old = int(node.value)
                new = pairs[old]
                # Both Chinese controller-identity proxies deliberately retain state 527.
                if relative == "common/national_focus/china_shared_TSR.txt" and node.key == "controls_state" and old == 527 and any(a.key == "525" for a in _ancestors(node)):
                    return raw
                if node.key == "state":
                    return f"OR = {{ {raw} {node.key} = {new} }}"
                if node.key in CONDITIONS:
                    return f"AND = {{ {raw} {node.key} = {new} }}"
                if node.key in TRANSFERS:
                    return raw + newline + _indent(text, node.start) + f"{node.key} = {new}"
                return raw
            if node.key in {"generator", "states", "prioritize"} and node.children and all(not n.op and n.key.isdigit() for n in node.children):
                values = [int(n.key) for n in node.children]
                if node.key == "prioritize" and len(values) == 1:
                    return raw  # Explicit single preferred facility site remains single.
                edits = [(n.start-node.start, n.end-node.start, f"{n.key} {pairs[int(n.key)]}")
                         for n in node.children if int(n.key) in pairs]
                return _splice(raw, edits)
            if node.key.isdigit() and int(node.key) in pairs:
                old = int(node.key)
                if relative == "common/national_focus/japan.txt":
                    forts = _fort_scopes(text, node, raw, pairs[old], newline)
                    if forts is not None:
                        return forts
                # Capacity and single-location industrial rewards stay at the retained site.
                if any(c.key == "free_building_slots" for c in node.children):
                    return raw
                rendered = _splice(raw, [(c.start-node.start, c.end-node.start, render(c)) for c in node.children])
                if _condition(node):
                    indent = _indent(text, node.start)
                    return (f"AND = {{{newline}{indent}\t{rendered}{newline}{indent}\t" +
                            _scope_clone(rendered, old, pairs[old]) + f"{newline}{indent}}}")
                safe_effects = {"start_resistance", "set_compliance", "set_resistance", "set_garrison_strength",
                                "set_demilitarized_zone", "add_core_of", "remove_core_of", "set_state_flag", "clr_state_flag"}
                if node.children and all(c.key in safe_effects for c in node.children):
                    return rendered + newline + _indent(text, node.start) + _scope_clone(rendered, old, pairs[old])
                return rendered
            return _splice(raw, [(c.start-node.start, c.end-node.start, render(c)) for c in node.children])

        result = _splice(text, [(n.start, n.end, render(n)) for n in nodes])
    if result == text:
        raise SplitSharedError(f"shared split made no reviewed change: {relative}")
    parse(result)
    return (b"\xef\xbb\xbf" if bom else b"") + (HEADER + newline + result).encode("utf-8")


def remove_shared(relative: str, data: bytes, state_id_map: Mapping[int, int], *, before: bytes,
                  expected_after_sha256: str | None = None) -> bytes:
    """Restore exact frozen predecessor bytes only after full forward replay matches."""
    if expected_after_sha256 is not None and hashlib.sha256(data).hexdigest().upper() != expected_after_sha256.upper():
        raise SplitSharedError(f"shared split output hash mismatch: {relative}")
    if apply_shared(relative, before, state_id_map) != data:
        raise SplitSharedError(f"shared split cannot reverse independently changed output: {relative}")
    return before


#20261108_kpopmodder: Reuse the existing nine-state Korean hooks as a pure transform of the new pinned host bytes.
def updated_host_intermediate(relative: str, data: bytes) -> bytes:
    """Apply the pre-split Korean hooks to one exact reviewed 196 host input.

    This is the same nine-state transformation used by the older East-Asia
    producer, with caller-supplied bytes instead of an implicit live-file read.
    The separate host-update layer owns source snapshots and final output pins.
    """
    relative = Path(relative).as_posix()
    if relative not in UPDATED_HOST_SHA256:
        return data
    if hashlib.sha256(data).hexdigest().upper() != UPDATED_HOST_SHA256[relative]:
        raise SplitSharedError(f"updated RT56 shared input drift: {relative}")
    import build_east_asia_overrides as east

    bom = data.startswith(b"\xef\xbb\xbf")
    text = data.decode("utf-8-sig")
    crlf = text.count("\r\n")
    if crlf and re.search(r"(?<!\r)\n", text):
        raise SplitSharedError(f"mixed updated shared input line endings: {relative}")
    fmt = east.TextFormat("\r\n" if crlf else "\n", bom, text.endswith(("\n", "\r")))
    text = text.replace("\r\n", "\n")
    if relative == "common/on_actions/14_sea_on_actions.txt":
        text = east.expand_command_sequence(
            text, "state", (918, 917, 919, 920, 527), (1144, 1145, 1146), 1,
            "updated SEA resistance state initialization",
        )
    else:
        source_ids = (527, 917, 918, 919, 920, 525)
        found = []
        for state_id in source_ids:
            matches = [(start, end, text[start:end])
                       for start, end in east.assignment_blocks(text, str(state_id))
                       if "start_resistance = yes" in text[start:end]
                       and "set_compliance = 15" in text[start:end]
                       and "set_resistance = 1" in text[start:end]]
            if len(matches) != 1:
                raise SplitSharedError(f"updated JAP history resistance block changed: {state_id}")
            found.append(matches[0])
        ordered = sorted(found)
        start, end = ordered[0][0], ordered[-1][1]
        between = text[start:end]
        if any(between.count(f"{state_id} = {{") != 1 for state_id in source_ids):
            raise SplitSharedError("updated JAP history Korean resistance blocks no longer contiguous")
        template = found[0][2]
        body = template[template.find("{") + 1:template.rfind("}")]
        body = re.sub(r"^\n", "", body)
        body = re.sub(r"\n$", "", body)
        lines = ["# HOK starts independent in 1936; initialize RT56-equivalent resistance on annexation.",
                 "1939.3.14 = {"]
        for state_id in east.ALL_KOREA:
            lines.append(f"\t{state_id} = {{")
            lines.extend("\t" + line for line in body.split("\n"))
            lines.append("\t}")
        lines.append("}")
        text = text[:start] + "\n".join(lines) + text[end:]
    parse(text)
    return east.encode_text(text, fmt)


def rebase_updated_host(relative: str, data: bytes, state_id_map: Mapping[int, int]) -> bytes:
    """Compose the reviewed nine-state hook and existing fifteen-state split."""
    relative = Path(relative).as_posix()
    if relative not in UPDATED_HOST_SHA256:
        return data
    return apply_shared(relative, updated_host_intermediate(relative, data), state_id_map)


